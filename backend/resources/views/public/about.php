  <h1>City Solutions is a multi-module city service platform.</h1>
  <p>City Solutions is built to combine local commerce, grocery mart, service bookings, medicine delivery workflows, hotels, restaurants, and real estate into one customer app with independent operational panels.</p>
  <h2>What we operate</h2>
  <ul>
    <li>Customer app experience with account, wallet, orders, bookings, refunds, support and zone-aware discovery.</li>
    <li>Admin panels for module settings, products, services, bookings, zones, complaints, refunds and reports.</li>
    <li>Partner panels for vendors, service providers, hotel owners and real estate agents.</li>
  </ul>
  <h2>Important note</h2>
  <p>City Solutions is a technology and operations platform. Actual availability, delivery, booking confirmation and service quality depend on approved local partners, inventory and zone coverage.</p>
