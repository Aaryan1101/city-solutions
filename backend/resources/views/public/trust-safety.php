<main class="legal">
  <span class="pill">Trust & Safety</span>
  <h1>Trust is built through checks, records and clear escalation.</h1>
  <div class="notice">For emergencies, users should contact local emergency services directly. App support is not a substitute for emergency response.</div>
  <h2>Customer protections</h2>
  <ul>
    <li>Order and booking histories are linked to the customer account or device guest identity.</li>
    <li>Refunds, cancellations and complaints are recorded for admin review.</li>
    <li>Zone-aware listings reduce unavailable products, services and properties.</li>
    <li>Uploaded media is validated and restricted for safer handling.</li>
  </ul>
  <h2>Partner protections</h2>
  <ul>
    <li>Business partners go through controlled onboarding before serving customers.</li>
    <li>Partner records, reviews, refunds and support activity can be reviewed for quality and dispute handling.</li>
    <li>Operational records are retained for invoice, dispute and support review.</li>
  </ul>
  <h2>Platform safeguards</h2>
  <p>The backend uses session hardening, rate limits, upload restrictions, route separation, security headers and production-safe error responses. Payment gateway and Firebase production credentials must be configured before live launch.</p>
